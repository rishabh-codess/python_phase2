# Easy Python snippet: greeting, even/odd check, and a multiplication table

# 1. Greeting
name = "Python"
print(f"Hello, {name}!")

# 2. Even or odd check
number = 7
if number % 2 == 0:
    print(f"{number} is even")
else:
    print(f"{number} is odd")

# 3. Multiplication table
table_of = 5
for i in range(1, 11):
    print(f"{table_of} x {i} = {table_of * i}")
